"""Feed forward network module for the future Transformer model.

This module will eventually define the position-wise feed forward network used
inside Transformer encoder and decoder blocks.
"""



import torch
import torch.nn as nn
class FeedForward(nn.Module):
    def __init__(self, d_model, d_ff):
        super().__init__()
        self.linear1 = nn.Linear(d_model, d_ff)
        self.relu = nn.ReLU()
        self.linear2 = nn.Linear(d_ff, d_model)

    def forward(self, x):
        x = self.linear1(x)
        x = self.relu(x)
        x = self.linear2(x)
        return x
